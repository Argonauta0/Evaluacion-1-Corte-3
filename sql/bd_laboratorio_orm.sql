CREATE DATABASE bd_laboratorio_orm;

-- 2. CREACIÓN DEL ESQUEMA
CREATE SCHEMA IF NOT EXISTS laboratorio;

-- 3. CREACIÓN DE TABLAS Y RESTRICCIONES DE INTEGRIDAD

-- Tabla padre: tipo_equipo
CREATE TABLE laboratorio.tipo_equipo (
                                         id_tipo     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         nombre      VARCHAR(100) NOT NULL,
                                         descripcion VARCHAR(250),
                                         CONSTRAINT uq_tipo_equipo_nombre UNIQUE (nombre)
);

-- Tabla hija: equipo
CREATE TABLE laboratorio.equipo (
                                    id_equipo   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    codigo      VARCHAR(50)  NOT NULL,
                                    nombre      VARCHAR(150) NOT NULL,
                                    marca       VARCHAR(100),
                                    estado      VARCHAR(30)  NOT NULL,
                                    cantidad    INTEGER      NOT NULL,
                                    id_tipo     BIGINT       NOT NULL,

    -- Restricciones de unicidad, dominio y referencia
                                    CONSTRAINT uq_equipo_codigo    UNIQUE (codigo),
                                    CONSTRAINT chk_equipo_cantidad CHECK (cantidad >= 0),
                                    CONSTRAINT chk_equipo_estado   CHECK (estado IN ('Disponible', 'En mantenimiento', 'Fuera de servicio')),
                                    CONSTRAINT fk_equipo_tipo      FOREIGN KEY (id_tipo)
                                        REFERENCES laboratorio.tipo_equipo (id_tipo)
                                        ON DELETE RESTRICT
                                        ON UPDATE CASCADE
);

